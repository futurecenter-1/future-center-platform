-- Email-first student onboarding and safe course enrollment requests.
-- Students may discover active courses without academic details, but a paid course
-- request is accepted only when the student's saved stage matches the course.
create table if not exists public.course_enrollment_requests (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.students(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id)
);

create unique index if not exists course_enrollment_requests_one_pending
  on public.course_enrollment_requests(student_id, course_id)
  where status = 'pending';

alter table public.course_enrollment_requests enable row level security;

revoke all on table public.course_enrollment_requests from anon, authenticated;
grant select, update on table public.course_enrollment_requests to authenticated;
grant insert (student_id, course_id) on table public.course_enrollment_requests to authenticated;
grant usage, select on sequence public.course_enrollment_requests_id_seq to authenticated;

drop policy if exists course_enrollment_requests_read_own
  on public.course_enrollment_requests;
create policy course_enrollment_requests_read_own
  on public.course_enrollment_requests
  for select to authenticated
  using (
    exists (
      select 1 from public.students s
      where s.id = course_enrollment_requests.student_id
        and s.auth_user_id = auth.uid()
    )
  );

drop policy if exists course_enrollment_requests_insert_eligible
  on public.course_enrollment_requests;
create policy course_enrollment_requests_insert_eligible
  on public.course_enrollment_requests
  for insert to authenticated
  with check (
    status = 'pending'
    and reviewed_at is null
    and reviewed_by is null
    and exists (
      select 1
      from public.students s
      join public.courses c on c.id = course_enrollment_requests.course_id
      join public.stages st on st.id = c.stage_id
      where s.id = course_enrollment_requests.student_id
        and s.auth_user_id = auth.uid()
        and c.active = true
        and c.is_public = false
        and s.stage_id = c.stage_id
        and s.university_id = st.university_id
    )
  );

drop policy if exists course_enrollment_requests_admin_manage
  on public.course_enrollment_requests;
create policy course_enrollment_requests_admin_manage
  on public.course_enrollment_requests
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create or replace function public.admin_process_course_enrollment_request(
  p_request_id bigint,
  p_approve boolean
)
returns void
language plpgsql
security invoker
set search_path = public
as $function$
declare
  req public.course_enrollment_requests%rowtype;
  eligible boolean;
  already_subscribed boolean;
begin
  if not public.is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;

  select * into req
  from public.course_enrollment_requests
  where id = p_request_id
  for update;

  if not found then
    raise exception 'Enrollment request not found';
  end if;
  if req.status <> 'pending' then
    raise exception 'This enrollment request has already been reviewed';
  end if;

  if p_approve then
    select exists (
      select 1
      from public.students s
      join public.courses c on c.id = req.course_id
      join public.stages st on st.id = c.stage_id
      where s.id = req.student_id
        and c.active = true
        and c.is_public = false
        and s.stage_id = c.stage_id
        and s.university_id = st.university_id
    ) into eligible;

    if not eligible then
      raise exception 'Student academic details no longer match this course';
    end if;

    select exists (
      select 1 from public.student_courses sc
      where sc.student_id = req.student_id
        and sc.course_id = req.course_id
        and sc.active = true
        and (sc.expires_at is null or sc.expires_at > now())
    ) into already_subscribed;

    if not already_subscribed then
      insert into public.student_courses(student_id, course_id, active, expires_at)
      values (req.student_id, req.course_id, true, null);
    end if;

    update public.course_enrollment_requests
    set status = 'approved', reviewed_at = now(), reviewed_by = auth.uid()
    where id = req.id;
  else
    update public.course_enrollment_requests
    set status = 'rejected', reviewed_at = now(), reviewed_by = auth.uid()
    where id = req.id;
  end if;
end;
$function$;

revoke all on function public.admin_process_course_enrollment_request(bigint, boolean)
  from public, anon, authenticated;
grant execute on function public.admin_process_course_enrollment_request(bigint, boolean)
  to authenticated;
